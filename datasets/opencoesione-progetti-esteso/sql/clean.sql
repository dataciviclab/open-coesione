-- clean.sql — OpenCoesione Progetti Esteso (199 colonne → ~77 selezionate)
-- Input: raw_input (parquet esteso 2021-2027)
-- Output: progetti puliti con geolocalizzazione, programmi, indicatori

SELECT
  -- Identificativi
  COD_LOCALE_PROGETTO,
  CUP,
  OC_LINK,

  -- Titolo e descrizione
  OC_TITOLO_PROGETTO,
  OC_SINTESI_PROGETTO,

  -- Ciclo di programmazione
  OC_COD_CICLO,
  OC_DESCR_CICLO,

  -- Tema
  OC_COD_TEMA_SINTETICO,
  OC_TEMA_SINTETICO,

  -- Grande progetto
  COD_GRANDE_PROGETTO,
  DESCRIZIONE_GRANDE_PROGETTO,

  -- Programma completo
  OC_COD_FONTE,
  OC_DESCR_FONTE,
  FONDO_COMUNITARIO,
  OC_CODICE_PROGRAMMA,
  OC_DESCRIZIONE_PROGRAMMA,
  COD_OB_TEMATICO,
  DESCR_OB_TEMATICO,
  COD_PRIORITA_INVEST,
  DESCR_PRIORITA_INVEST,

  -- Articolazione programma
  OC_COD_CATEGORIA_SPESA,
  OC_DESCR_CATEGORIA_SPESA,
  OC_ARTICOLAZIONE_PROGRAMMA,
  OC_COD_ARTICOLAZ_PROGRAMMA,
  OC_DESCR_ARTICOLAZ_PROGRAMMA,
  OC_SUBARTICOLAZIONE_PROGRAMMA,
  OC_COD_SUBARTICOLAZ_PROGRAMMA,
  OC_DESCR_SUBARTICOLAZ_PROGRAMMA,

  -- Dettagli CUP
  CUP_COD_NATURA,
  CUP_DESCR_NATURA,
  CUP_COD_SETTORE,
  CUP_DESCR_SETTORE,
  CUP_COD_CATEGORIA,
  CUP_DESCR_CATEGORIA,

  -- Tipo aiuto
  OC_COD_TIPO_AIUTO,
  OC_DESCR_TIPO_AIUTO,

  -- Geolocalizzazione
  COD_REGIONE,
  DEN_REGIONE,
  COD_PROVINCIA,
  DEN_PROVINCIA,
  COD_COMUNE,
  DEN_COMUNE,
  OC_MACROAREA,

  -- Settore economico
  COD_ATECO,
  DESCRIZIONE_ATECO,

  -- Stati
  OC_STATO_PROGETTO,
  OC_STATO_PROCEDURALE,
  OC_STATO_FINANZIARIO,
  OC_COD_FASE_CORRENTE,
  OC_DESCR_FASE_CORRENTE,

  -- Date progetto
  OC_DATA_INIZIO_PROGETTO,
  OC_DATA_FINE_PROGETTO_PREVISTA,
  OC_DATA_FINE_PROGETTO_EFFETTIVA,

  -- Finanziamenti
  FINANZ_UE,
  FINANZ_UE_FESR,
  FINANZ_UE_FSE,
  FINANZ_STATO_FSC,
  FINANZ_REGIONE,
  FINANZ_PROVINCIA,
  FINANZ_COMUNE,
  FINANZ_PRIVATO,
  FINANZ_TOTALE_PUBBLICO,

  -- Costo e realizzazione
  OC_COSTO_COESIONE,
  COSTO_REALIZZATO,
  COSTO_RENDICONTABILE_UE,

  -- Impegni
  IMPEGNI,
  OC_IMPEGNI_COESIONE,

  -- Pagamenti
  TOT_PAGAMENTI,
  OC_TOT_PAGAMENTI_BENEFICIARI,
  OC_TOT_PAGAMENTI_RENDICONTAB_UE,
  OC_PAGAMENTI_COESIONE,

  -- Indicatori
  COD_INDICATORE_1,
  DESCR_INDICATORE_1,
  UNITA_MISURA_INDICATORE_1,
  PROGRAMMATO_INDICATORE_1,
  REALIZZATO_INDICATORE_1,

  -- Data aggiornamento
  DATA_AGGIORNAMENTO

FROM raw_input
WHERE COD_LOCALE_PROGETTO IS NOT NULL
  AND trim(COD_LOCALE_PROGETTO) <> ''
