-- clean.sql — OpenCoesione impegni (storico)
-- Input: raw_input (impegni_20260630.parquet)
-- OC_DATA_IMPEGNI è INTEGER YYYYMMDD → CAST anno intero.

SELECT
  COD_LOCALE_PROGETTO,
  OC_DATA_IMPEGNI,
  CAST(OC_DATA_IMPEGNI / 10000 AS INTEGER) AS anno,
  IMPEGNI,
  OC_TIPO_IMPEGNI
FROM raw_input
WHERE COD_LOCALE_PROGETTO IS NOT NULL
  AND trim(COD_LOCALE_PROGETTO) <> ''
  AND OC_DATA_IMPEGNI IS NOT NULL
  AND OC_DATA_IMPEGNI >= 19900101
